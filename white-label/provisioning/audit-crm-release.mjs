// Source-only, non-deploying audit for the dedicated test CRM application.
// This file reads code from disk. It never invokes Netlify, Supabase, Auth,
// shell commands, or a remote provider; it never asks for credentials.
import {readFile,lstat} from "node:fs/promises";
import {createHash} from "node:crypto";
import {resolve,join,relative,isAbsolute} from "node:path";
import {
  RELEASE_CONTENT,RELEASE_PILOT_SITE_ID,RELEASE_PILOT_SUPABASE,
  RELEASE_PILOT_URL,
} from "./prepare-crm-release.mjs";

const REF = new URL(RELEASE_PILOT_SUPABASE).hostname.split(".")[0];
const DANGEROUS = [
  /\bsb_secret_[A-Za-z0-9_-]{16,}\b/,
  /\bservice_role\s*[:=]\s*["'][^"']+/i,
  /\b(?:DATABASE_URL|SUPABASE_SERVICE_ROLE_KEY|NETLIFY_AUTH_TOKEN)\s*[:=]\s*["'][^"']+/i,
];
const FILE_SIZE_CAP = 600000;

function insist(condition,reason) {
  if (!condition) throw new Error("pilot_release_audit_failed:"+reason);
}
function checkedPath(root,filename) {
  insist(typeof filename==="string" && !filename.includes("\\") &&
    filename.split("/").every(part=>part && part!=="." && part!==".."),"unsafe_path");
  const path=resolve(root,filename);
  const part=relative(root,path);
  insist(part!=="" && !part.startsWith("..") && !isAbsolute(part),"escaped_root");
  return path;
}

export async function auditPilotReleaseSource(sourceDir, fs={readFile,lstat}) {
  insist(typeof sourceDir==="string" && isAbsolute(sourceDir),"invalid_source_directory");
  const root=resolve(sourceDir);
  const checked = new Map();
  for(const filename of [...RELEASE_CONTENT,"manifest.json"]) {
    const path=checkedPath(root,filename);
    // Each entry must be a genuine regular file. In particular, a source
    // symlink cannot copy unrelated repository files into the release.
    const info=await fs.lstat(path);
    insist(info.isFile() && !info.isSymbolicLink() &&
      info.size>0 && info.size<=FILE_SIZE_CAP,"unsafe_asset:"+filename);
    const bytes=await fs.readFile(path);
    insist(bytes instanceof Uint8Array &&
      bytes.byteLength>0 && bytes.byteLength<=FILE_SIZE_CAP,"invalid_asset:"+filename);
    checked.set(filename,bytes.toString("utf8"));
  }

  let manifest;
  try{manifest=JSON.parse(checked.get("manifest.json"));}
  catch{throw new Error("pilot_release_audit_failed:invalid_manifest");}
  insist(manifest?.deployable===false &&
    manifest?.customerSiteDeployed===false &&
    manifest?.ownerInvitationConfigured===false &&
    manifest?.invitationSendingConfigured===false &&
    manifest?.ownerBootstrapImplemented===false &&
    manifest?.readOnly===true &&
    manifest?.targetSite===RELEASE_PILOT_URL &&
    manifest?.targetProject===REF,"manifest_safety_state");
  insist(Array.isArray(manifest.includedFiles) &&
    manifest.includedFiles.length===RELEASE_CONTENT.length &&
    JSON.stringify([...manifest.includedFiles].sort())===
      JSON.stringify([...RELEASE_CONTENT].sort()),"asset_allowlist_mismatch");

  // A JSON key (even publishable) MUST be generated by the approved packager.
  // Nothing credential-like should ever be checked in to the source directory.
  try {
    await fs.lstat(checkedPath(root,"tenant-config.json"));
    throw new Error("pilot_release_audit_failed:embedded_credentials");
  } catch(err) {
    if(err?.code!=="ENOENT") throw err;
  }

  const html=checked.get("index.html");
  const callback=checked.get("auth/callback/index.html");
  const app=checked.get("app.mjs");
  const callbackJs=checked.get("invite-callback.mjs");
  const client=checked.get("tenant.mjs");
  const headers=checked.get("_headers");
  const redirects=checked.get("_redirects");

  for(const filename of RELEASE_CONTENT) {
    const value=checked.get(filename);
    insist(!DANGEROUS.some(pattern=>pattern.test(value)),"sensitive_source:"+filename);
  }
  insist(!/<script(?![^>]*\bsrc=)[^>]*>/i.test(html+callback) &&
    !/\bon[a-z]+\s*=/i.test(html+callback) &&
    !/<iframe\b/i.test(html+callback),"unsafe_html");
  insist(/src="\.\/app\.mjs"/.test(html) &&
    /href="\.\/styles\.css"/.test(html) &&
    /src="\.\.\/\.\.\/invite-callback\.mjs"/.test(callback) &&
    /href="\.\.\/\.\.\/styles\.css"/.test(callback),"broken_page_assets");
  insist(/["']\.\/tenant\.mjs["']/.test(app+callbackJs) &&
    /["']\.\/invite-link\.mjs["']/.test(callbackJs),"broken_module_imports");
  insist(/window\.history\.replaceState\(/.test(callbackJs) &&
    callbackJs.indexOf("window.history.replaceState(")<
    callbackJs.indexOf("await fetch(") &&
    callbackJs.indexOf('accept.addEventListener("click"')<
    callbackJs.indexOf("client.acceptInvitation("),"invite_token_flow");
  insist(/fetch\(["']\.\/tenant-config\.json["']/.test(app) &&
    /fetch\(["']\.\.\/\.\.\/tenant-config\.json["']/.test(callbackJs),
    "missing_tenant_config_gate");
  insist(/const PILOT_REF = ["']nlupgjwcyivepzgqffss["']/.test(client) &&
    /const PILOT_CRM_ORIGIN = ["']https:\/\/kleanly-business-crm-pilot\.netlify\.app["']/.test(client) &&
    !/localStorage|sessionStorage|innerHTML/.test(client+callbackJs+app),
    "isolation_or_session_storage");
  insist(headers.includes("X-Robots-Tag: noindex, nofollow") &&
    headers.includes("X-Frame-Options: DENY") &&
    headers.includes("Referrer-Policy: no-referrer") &&
    headers.includes("Cache-Control: no-store") &&
    headers.includes("frame-ancestors 'none'") &&
    headers.includes("script-src 'self'") &&
    headers.includes("connect-src 'self' "+RELEASE_PILOT_SUPABASE) &&
    !/unsafe-inline|unsafe-eval/.test(headers),"missing_security_headers");
  insist(redirects.split("\n").filter(Boolean).length===2 &&
    redirects.includes("/auth/callback /auth/callback/index.html 200") &&
    redirects.includes("/auth/callback/ /auth/callback/index.html 200"),
    "missing_auth_callback_route");
  const files=RELEASE_CONTENT.map(filename=>({
    filename,
    sha256:createHash("sha256").update(checked.get(filename),"utf8").digest("hex"),
  }));
  const sourceHash=createHash("sha256").update(
    files.map(({filename,sha256})=>filename+":"+sha256).join("\n")
  ).digest("hex");
  return Object.freeze({
    audit:"source-only",
    sourceValidated:true,
    noPublishableKeyBundled:true,
    noSecretKeysBundled:true,
    siteId:RELEASE_PILOT_SITE_ID,
    siteUrl:RELEASE_PILOT_URL,
    projectUrl:RELEASE_PILOT_SUPABASE,
    filesChecked:files.length,
    sourceHash,
    privateDatabaseChanged:false,
    ownerInvitationSent:false,
    websiteDeployed:false,
    readyForSeparateDeploymentApproval:false,
    remainingPrerequisites:[
      "Verify the target Free Plan test team and site through its own Netlify OAuth connection",
      "Verify the target Supabase Auth, project API grants and publishable key through the test account",
      "Build and review the real first-owner onboarding and live RLS test plan",
      "Obtain a separate deployment approval before uploading to the empty test site",
    ],
  });
}
